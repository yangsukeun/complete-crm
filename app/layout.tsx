import type { Metadata } from "next";
import { headers } from "next/headers";
import Script from "next/script";
import { Toaster } from "sonner";
import { getClientIp, ensureAccessLog } from "@/lib/access-log";
import { authWithTimeout } from "@/lib/auth-safe";
import { Providers } from "@/components/providers";
import { AppNav } from "@/components/app-nav";
import { OneSignalUserSync } from "@/components/OneSignalUserSync";
import "./globals.css";

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

// layout에서 headers() 사용으로 정적 렌더 불가. 동적 렌더 명시해 빌드/런타임 오류 방지.
export const dynamic = "force-dynamic";

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const h = await headers();
  const pathname = h.get("x-pathname") ?? "";
  const isPublicPage =
    pathname === "/login" ||
    pathname === "/signup" ||
    pathname.startsWith("/login/");

  let session: Awaited<ReturnType<typeof authWithTimeout>> = null;
  if (!isPublicPage) {
    try {
      session = await authWithTimeout();
      if (session?.user?.id) {
        // 성능: 프로덕션에서는 초기 렌더마다 DB를 치지 않도록 기본 비활성화
        if (
          process.env.NODE_ENV === "development" ||
          process.env.ENABLE_ACCESS_LOG === "true"
        ) {
          void ensureAccessLog(
            session.user.id,
            getClientIp(h),
            h.get("user-agent") ?? ""
          ).catch((e: unknown) => console.error("[AccessLog] 기록 실패:", e));
        }
      }
    } catch (e) {
      console.error("[layout] auth failed", e);
    }
  }

  return (
    <html lang="en">
      <body className="antialiased">
        {(typeof process.env.NEXT_PUBLIC_ONESIGNAL_APP_ID === "string" && process.env.NEXT_PUBLIC_ONESIGNAL_APP_ID.trim() !== "") ? (
          <>
            <Script
              src="https://cdn.onesignal.com/sdks/web/v16/OneSignalSDK.page.js"
              strategy="lazyOnload"
            />
            <Script id="onesignal-init" strategy="lazyOnload">
              {`(function(){
                var appId = "${(process.env.NEXT_PUBLIC_ONESIGNAL_APP_ID ?? "").trim()}";
                if (!appId) return;
                window.OneSignalDeferred = window.OneSignalDeferred || [];
                OneSignalDeferred.push(async function(OneSignal) {
                  try { await OneSignal.init({ appId: appId }); } catch (e) { console.warn("[OneSignal] init skipped:", e && e.message ? e.message : e); }
                });
              })();`}
            </Script>
          </>
        ) : null}
        <Providers session={session ?? undefined}>
          <OneSignalUserSync />
          <AppNav />
          <main>{children}</main>
          <Toaster richColors position="top-center" />
        </Providers>
      </body>
    </html>
  );
}
